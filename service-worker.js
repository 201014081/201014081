const CACHE_NAME = "lab-stem-energia-v3";
const ASSETS = [
  "./",
  "./index.html",
  "./style.css",
  "./app.js",
  "./manifest.json",
  "./icons/icon-192.png",
  "./icons/icon-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          // Solo cachear respuestas válidas de mismo origen
          if (!response || response.status !== 200 || response.type !== "basic") {
            return response;
          }
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => {
          // CORRECCIÓN 1: Fallback seguro cuando no hay cache ni red
          // (si hubiera versión en cache ya se habría devuelto arriba, antes de intentar fetch)
          return new Response(
            "<h1>Sin conexión</h1><p>Esta aplicación necesita conexión la primera vez.</p>",
            { status: 503, headers: { "Content-Type": "text/html" } }
          );
        });
    })
  );
});
